"""Generate lecture 17 TikZ figures using only the Python standard library.

Coordinates reconstruct the board's examples; they are illustrative, not data.
Collision checks include boundary contact. Quadtree classification uses cell
interiors, while executable paths and portals are checked separately.
"""
from pathlib import Path
from math import hypot, sin, cos, pi
import heapq
import random

OUT = Path(__file__).resolve().parents[1] / 'figures' / 'lecture13'
EPS = 1e-9


def p(a):
    return f'({a[0]:.4f},{a[1]:.4f})'


def chain(points):
    return ' -- '.join(map(p, points))


def area(poly):
    return abs(sum(a[0]*b[1]-a[1]*b[0]
                   for a, b in zip(poly, poly[1:]+poly[:1]))) / 2


def clip(poly, axis, bound, sign):
    result = []
    for a, b in zip(poly, poly[1:]+poly[:1]):
        ia, ib = sign*(a[axis]-bound) >= 0, sign*(b[axis]-bound) >= 0
        if ia:
            result.append(a)
        if ia != ib:
            t = (bound-a[axis])/(b[axis]-a[axis])
            result.append(tuple(a[k]+t*(b[k]-a[k]) for k in (0, 1)))
    return result


def cross(a, b, c):
    return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])


def on(a, b, c):
    return abs(cross(a, b, c)) < EPS and all(
        min(a[k], b[k])-EPS <= c[k] <= max(a[k], b[k])+EPS for k in (0, 1))


def intersects(a, b, c, d):
    return (cross(a,b,c)*cross(a,b,d) < -EPS and
            cross(c,d,a)*cross(c,d,b) < -EPS) or any(
                (on(a,b,c), on(a,b,d), on(c,d,a), on(c,d,b)))


def inside(q, poly):
    if any(on(a,b,q) for a,b in zip(poly, poly[1:]+poly[:1])):
        return True
    hit = False
    for a,b in zip(poly, poly[1:]+poly[:1]):
        if (a[1] > q[1]) != (b[1] > q[1]):
            if q[0] < a[0]+(q[1]-a[1])*(b[0]-a[0])/(b[1]-a[1]):
                hit = not hit
    return hit


def free(a, b, obstacles):
    return not any(inside(a,o) or inside(b,o) or any(
        intersects(a,b,c,d) for c,d in zip(o,o[1:]+o[:1])) for o in obstacles)


def path_search(nodes, edges, start, goal):
    adj = {i: [] for i in range(len(nodes))}
    for i,j in edges:
        w = hypot(nodes[i][0]-nodes[j][0], nodes[i][1]-nodes[j][1])
        adj[i].append((j,w)); adj[j].append((i,w))
    dist, prev, queue = {start:0}, {}, [(0,start)]
    while queue:
        cost,u = heapq.heappop(queue)
        if cost != dist[u]:
            continue
        if u == goal:
            route = [u]
            while route[-1] != start:
                route.append(prev[route[-1]])
            return route[::-1]
        for v,w in adj[u]:
            if cost+w < dist.get(v, float('inf')):
                dist[v],prev[v] = cost+w,u
                heapq.heappush(queue,(cost+w,v))
    return []


def save(name, lines, scale=1):
    OUT.mkdir(parents=True, exist_ok=True)
    header = '% Generated by tools/generate_sampling_figures.py\n'
    body = [rf'\begin{{tikzpicture}}[scale={scale},line cap=round,line join=round,',
            r' every node/.style={font=\footnotesize},>=Stealth]']
    (OUT / (name+'.tex')).write_text(header+'\n'.join(body+lines+[r'\end{tikzpicture}'])+'\n', encoding='utf-8')


def obstacle_commands(obstacles):
    return [r'\fill[black!85] '+chain(o)+' -- cycle;' for o in obstacles]


def quadtree():
    obs = [[(1.8,5.2),(2.7,7),(3.7,5.2)],
           [(4,2),(6,2),(6,2.5),(6.8,2.5),(6.8,6.7),(5,6.7),(5,6),(4,6)]]
    start,goal = (.4,7.3),(7.5,1.3)
    def status(c):
        x,y,s = c
        occupied = 0
        for o in obs:
            q = o
            for axis,bound,sign in [(0,x,1),(0,x+s,-1),(1,y,1),(1,y+s,-1)]:
                q = clip(q,axis,bound,sign)
            occupied += area(q)
        return 'free' if occupied < EPS else ('occupied' if abs(occupied-s*s)<EPS else 'mixed')
    def portal(a,b):
        x,y,s = a; X,Y,S = b
        lo,hi = max(y,Y),min(y+s,Y+S)
        if hi-lo > EPS and (abs(x+s-X)<EPS or abs(X+S-x)<EPS):
            return (max(x,X),(lo+hi)/2)
        lo,hi = max(x,X),min(x+s,X+S)
        if hi-lo > EPS and (abs(y+s-Y)<EPS or abs(Y+S-y)<EPS):
            return ((lo+hi)/2,max(y,Y))
    cells = [(0,0,4),(4,0,4),(0,4,4),(4,4,4)]
    lines=[]
    for level in range(3):
        states=list(map(status,cells))
        centers=[(x+s/2,y+s/2) for x,y,s in cells]
        edges=[]; portals={}
        for i,a in enumerate(cells):
            for j in range(i):
                m=portal(a,cells[j])
                if m and 'occupied' not in (states[i],states[j]):
                    if states[i]==states[j]=='free' and not free(m,m,obs):
                        continue
                    edges.append((i,j)); portals[i,j]=portals[j,i]=m
        def cellof(q):
            return next(i for i,(x,y,s) in enumerate(cells) if x<q[0]<x+s and y<q[1]<y+s)
        si,gi=cellof(start),cellof(goal)
        use_edges=edges if level<2 else [(i,j) for i,j in edges if states[i]==states[j]=='free']
        route=path_search(centers,use_edges,si,gi)
        assert route, (level,states)
        if level<2:
            assert any(states[i]=='mixed' for i in route)
        geometric=[start,centers[si]]
        for i,j in zip(route,route[1:]):
            geometric += [portals[i,j],centers[j]]
        geometric.append(goal)
        if level==2:
            assert all(free(a,b,obs) for a,b in zip(geometric,geometric[1:]))
        lines.append(rf'\begin{{scope}}[yshift={-9.4*level}cm]')
        lines.append(rf'\node[anchor=west,font=\small\bfseries] at (0,8.6) {{Iteration {level+1}: {len(cells)} cells}};')
        for (x,y,s),st in zip(cells,states):
            fill={'free':'white','mixed':'black!12','occupied':'black!65'}[st]
            lines.append(rf'\fill[{fill}] {p((x,y))} rectangle {p((x+s,y+s))};')
        lines+=obstacle_commands(obs)
        for x,y,s in cells:
            lines.append(r'\draw[black!45,thin] '+p((x,y))+' rectangle '+p((x+s,y+s))+';')
        lines.append(r'\draw[thick] (0,0) rectangle (8,8);')
        if level==2:
            lines.append(r'\draw[robotframe,very thick] '+chain(geometric)+';')
        for q,label in [(start,'q_S'),(goal,'q_G')]:
            lines.append(r'\fill[robotframe] '+p(q)+r' circle (2pt);')
            lines.append(r'\node[fill=white,inner sep=1pt,above right] at '+p(q)+' {$'+label+'$};')
        lines.append(r'\begin{scope}[xshift=9.5cm]')
        lines.append(r'\draw[black!20] (0,0) rectangle (8,8);')
        for i,j in edges:
            lines.append(r'\draw[black!50] '+chain([centers[i],centers[j]])+';')
        lines.append(r'\draw[robotframe,very thick] '+chain([centers[i] for i in route])+';')
        for i,c in enumerate(centers):
            if states[i]=='occupied': continue
            fill='white' if states[i]=='free' else 'black!40'
            lines.append(rf'\draw[fill={fill}] '+p(c)+r' circle (3pt);')
        for i,label in [(si,'S'),(gi,'G')]:
            lines.append(r'\node[above left,fill=white,inner sep=1pt] at '+p(centers[i])+' {$C_'+label+'$};')
        lines.extend([r'\end{scope}',r'\end{scope}'])
        print(f'Quadtree {level+1}: {len(cells)} cells, {states.count("occupied")} occupied, route {len(route)} cells')
        if level<2:
            cells=[child for c,st in zip(cells,states) for child in
                   ([(c[0]+dx*c[2]/2,c[1]+dy*c[2]/2,c[2]/2) for dx,dy in [(0,0),(1,0),(0,1),(1,1)]]
                    if st=='mixed' else [c])]
    save('quadtree',lines,.65)


def prm():
    obs=[[(2.5,1),(4,2.5),(4.5,.8)],[(6,1.2),(7.8,1.2),(8,2.7),(6.1,2.7)]]
    domain=[(0,0),(10,0),(9.3,3.7),(3,3.3)]
    nodes=[(3,2.95),(8.5,.6),(2.1,.65),(4.1,.45),(4.9,1.8),(6,3),(8.3,2.1),
           (2,1.5),(4.6,2.9),(5.7,.5),(7,.5),(8.7,3.1),
           (2.8,2),(3,.4),(5.8,1.6),(8.6,1.3),(7.4,3.2)]
    assert all(inside(q,domain) and free(q,q,obs) for q in nodes)
    edges=[(i,j) for i,a in enumerate(nodes) for j,b in enumerate(nodes[:i])
           if hypot(a[0]-b[0],a[1]-b[1])<2.25 and free(a,b,obs)]
    route=path_search(nodes,edges,0,1); assert route
    lines=[r'\draw[thick] '+chain(domain)+' -- cycle;']+obstacle_commands(obs)
    for i,j in edges:
        lines.append(r'\draw[black!40] '+chain([nodes[i],nodes[j]])+';')
    rejected=(12,4)
    assert not free(nodes[rejected[0]],nodes[rejected[1]],obs)
    lines.append(r'\draw[red!75!black,dashed,thick] '+chain([nodes[i] for i in rejected])+';')
    lines.append(r'\draw[robotframe,very thick] '+chain([nodes[i] for i in route])+';')
    for i,q in enumerate(nodes):
        color='black' if i<2 else ['sensorframe','orange!90!black','green!50!black'][(i-2)//5]
        lines.append(rf'\draw[{color},fill=white,thick] '+p(q)+r' circle (2.5pt);')
    for q in [(3.7,1.5),(6.8,1.8)]:
        lines.append(r'\node[red,font=\large] at '+p(q)+r' {$\times$};')
    for i,label,pos in [(0,'q_S','above'),(1,'q_G','below')]:
        lines.append(rf'\node[{pos}] at '+p(nodes[i])+' {$'+label+'$};')
    lines.append(r'\node[anchor=west] at (0,-.5) {Samples: \textcolor{sensorframe}{batch 1}, \textcolor{orange!90!black}{batch 2}, \textcolor{green!50!black}{batch 3}};')
    save('prm',lines,1.35)
    print('PRM validated route:',route)


def local_tree():
    obs=[[(1.4,2.1),(2,3.4),(2.7,2.1)],[(5,1.1),(6.2,3.4),(7.5,1.1)]]
    lines=[r'\draw[thick] (0,0) rectangle (9,4.5);']+obstacle_commands(obs)
    root=(.45,4); frontier=[(root,-pi/4)]; rng=random.Random(17)
    colors=['robotframe','green!50!black','sensorframe','violet','orange!85!black']
    for depth in range(5):
        new=[]
        for a,heading in frontier:
            angles=[-70,-10,70,140,200] if depth==0 else [heading*180/pi-25+rng.uniform(-9,9),heading*180/pi+25+rng.uniform(-9,9)]
            for angle in angles:
                h=angle*pi/180; b=(a[0]+.9*cos(h),a[1]+.9*sin(h))
                valid=0<b[0]<9 and 0<b[1]<4.5 and free(a,b,obs)
                if valid:
                    lines.append(rf'\draw[{colors[depth]},thick] '+chain([a,b])+';')
                    lines.append(rf'\fill[{colors[depth]}] '+p(b)+r' circle (1.5pt);')
                    new.append((b,h))
                else:
                    lines.append(r'\draw[red!65,dashed] '+chain([a,b])+';')
                    lines.append(r'\node[red!65] at '+p(b)+r' {$\times$};')
        frontier=new
    lines.extend([r'\fill '+p(root)+r' circle (2pt) node[below right] {$q_S$};',
                  r'\fill (4.4,.65) circle (2pt) node[right] {$q_G$};',
                  r'\node[anchor=west] at (0,-.7) {Generations: \textcolor{robotframe}{1}, \textcolor{green!50!black}{2}, \textcolor{sensorframe}{3}, \textcolor{violet}{4}, \textcolor{orange!85!black}{5}};'])
    save('local-tree',lines,1.35)


def rrt_step():
    nodes=[(.5,.4),(1.3,1.3),(1,2.2),(2.5,1.8),(3.5,1.1),(3,3)]
    edges=[(0,1),(1,2),(1,3),(3,4),(3,5)]
    target=(7,2.6); near=min(range(len(nodes)),key=lambda i:hypot(nodes[i][0]-target[0],nodes[i][1]-target[1]))
    assert near==4
    a=nodes[near]; length=hypot(target[0]-a[0],target[1]-a[1]); d=1.4
    new=tuple(a[k]+d*(target[k]-a[k])/length for k in (0,1))
    lines=[r'\draw[black!20] (0,0) rectangle (8,4);']
    for i,j in edges: lines.append(r'\draw[thick] '+chain([nodes[i],nodes[j]])+';')
    for q in nodes: lines.append(r'\fill '+p(q)+r' circle (2pt);')
    lines += [r'\draw[sensorframe,dashed] '+chain([new,target])+';',
              r'\draw[sensorframe,very thick,->] '+chain([a,new])+r' node[midway,above left] {$d$};',
              r'\fill[sensorframe] '+p(new)+r' circle (2.5pt) node[below right] {$q_{\mathrm{new}}$};',
              r'\draw[sensorframe,thick] '+p(target)+r' circle (3pt) node[above] {$q_{\mathrm{rand}}$};',
              r'\node[below] at '+p(a)+r' {$q_{\mathrm{near}}$};',
              r'\node[below right] at '+p(nodes[0])+r' {$q_S$};']
    save('rrt-step',lines,1.35)


def bidirectional():
    obs=[[(2.6,.9),(6.1,.9),(6.4,2.7),(3,2.8)]]
    left=[(.6,3.5),(1.5,3.7),(2.4,4),(3.5,4.1),(1.1,2.4),(.5,1.5),(1.8,1.7),(2.3,1.2)]
    right=[(8.5,3.4),(7.8,3.9),(6.8,4.1),(5.5,4.1),(8,2.4),(8.5,1.5),(7.3,1.5),(6.8,.5)]
    edges=[(0,1),(1,2),(2,3),(0,4),(4,5),(4,6),(6,7)]
    lines=[r'\draw[thick] (0,0) rectangle (9,4.8);']+obstacle_commands(obs)
    for nodes,color in [(left,'sensorframe'),(right,'green!50!black')]:
        for i,j in edges:
            assert free(nodes[i],nodes[j],obs)
            lines.append(rf'\draw[{color},thick] '+chain([nodes[i],nodes[j]])+';')
        for q in nodes: lines.append(rf'\fill[{color}] '+p(q)+r' circle (2pt);')
    route=left[:4]+right[:4][::-1]
    assert all(free(a,b,obs) for a,b in zip(route,route[1:]))
    lines += [r'\draw[robotframe,very thick] '+chain(route)+';',
              r'\node[above] at (4.5,4.1) {connection};',
              r'\node[below left] at '+p(left[0])+r' {$q_S$};',
              r'\node[below right] at '+p(right[0])+r' {$q_G$};']
    save('bidirectional-tree',lines,1.35)


def integrate(q,w,t):
    x,y,h=q
    if w==0: return (x+t*cos(h),y+t*sin(h),h)
    return (x+(sin(h+w*t)-sin(h))/w,y-(cos(h+w*t)-cos(h))/w,h+w*t)


def primitives():
    lines=[r'\draw[thick] (0,0) rectangle (10,5);']
    for root,sgn,color,label in [((1,.7,pi/2),1,'robotframe','q_S'),((7.8,3.2,-pi/2),-1,'green!50!black','q_G')]:
        frontier=[root]
        for depth in range(3):
            new=[]
            for a in frontier:
                for w in [-.75,0,.75]:
                    points=[integrate(a,w,sgn*.95*i/20) for i in range(21)]
                    b=points[-1]
                    valid=all(0<q[0]<10 and 0<q[1]<5 for q in points)
                    if valid:
                        if sgn<0:
                            back=integrate(b,w,.95)
                            assert max(abs(back[i]-a[i]) for i in range(3))<1e-10
                        arrow='->' if sgn>0 else '<-'
                        lines.append(rf'\draw[{color}!{100-20*depth},{arrow}] '+chain(points)+';')
                        new.append(b)
                    else:
                        # Show just the first portion outside the domain.
                        cut=next(i for i,q in enumerate(points) if not(0<q[0]<10 and 0<q[1]<5))
                        lines.append(rf'\draw[{color}!50,dashed] '+chain(points[:cut+1])+';')
                        lines.append(rf'\node[{color}!70] at '+p(points[cut])+r' {$\times$};')
            frontier=new
        tip=(root[0]+.45*cos(root[2]),root[1]+.45*sin(root[2]))
        lines.extend([r'\fill '+p(root)+r' circle (2pt);',r'\draw[black,very thick,->] '+chain([root,tip])+';',
                      r'\node[below right] at '+p(root)+' {$'+label+'$};'])
    lines.append(r'\node[anchor=west] at (0,-.5) {\textcolor{robotframe}{Forward successors}\hspace{2cm}\textcolor{green!50!black}{Predecessors of the goal}};')
    save('motion-primitives',lines,1.3)


if __name__=='__main__':
    quadtree(); prm(); local_tree(); rrt_step(); bidirectional(); primitives()
